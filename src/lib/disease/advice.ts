export function getDiseaseGuidance(
  prediction: DiseasePrediction
): DiseaseGuidance {
  if (prediction.status !== "Rice Leaf" || !prediction.prediction) {
    return UNCERTAIN_GUIDANCE;
  }

  return GUIDANCE_BY_DISEASE[prediction.prediction.disease] ??
    UNCERTAIN_GUIDANCE;
}
