-- Rice Yield Thailand: analytical datasets for 77 provinces.
-- Yield is annual/crop-year data. Environment and NDVI are monthly data.

create table if not exists public.rice_provinces (
  id integer primary key,
  gid_1 text not null unique,
  province_en text not null,
  province_th text not null,
  region text not null check (region in ('North', 'Northeast', 'Central', 'South')),
  region_code text not null,
  boundary_geojson jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.rice_environment_monthly (
  id bigint generated by default as identity primary key,
  province_id integer not null references public.rice_provinces(id) on delete cascade,
  year integer not null check (year between 1900 and 2200),
  month integer not null check (month between 1 and 12),
  temperature_mean_c double precision,
  dewpoint_mean_c double precision,
  soil_moisture_mean double precision,
  rainfall_total_mm double precision,
  evaporation_total_mm double precision,
  solar_total_mj_m2 double precision,
  ndvi_mean double precision,
  ndvi_median double precision,
  ndvi_std double precision,
  ndvi_min double precision,
  ndvi_max double precision,
  rice_valid_ratio_mean double precision,
  rice_ndvi_imputed boolean not null default false,
  rice_ndvi_structural_missing boolean not null default false,
  rice_ndvi_final_quality text,
  grid_cell_count integer,
  created_at timestamptz not null default now(),
  constraint rice_environment_monthly_unique unique (province_id, year, month)
);

create table if not exists public.rice_yield_yearly (
  id bigint generated by default as identity primary key,
  province_id integer not null references public.rice_provinces(id) on delete cascade,
  crop_start_year integer not null check (crop_start_year between 1900 and 2200),
  crop_year text not null,
  actual_yield double precision not null,
  yield_per_harvested_rai double precision,
  production_ton double precision,
  harvested_area_rai double precision,
  planted_area_rai double precision,
  created_at timestamptz not null default now(),
  constraint rice_yield_yearly_unique unique (province_id, crop_start_year)
);

create table if not exists public.rice_yield_predictions (
  id bigint generated by default as identity primary key,
  province_id integer not null references public.rice_provinces(id) on delete cascade,
  crop_start_year integer not null check (crop_start_year between 1900 and 2200),
  crop_year text not null,
  actual_yield double precision not null,
  predicted_yield double precision not null,
  residual double precision not null,
  absolute_error double precision not null check (absolute_error >= 0),
  percentage_error double precision,
  model_version text not null,
  created_at timestamptz not null default now(),
  constraint rice_yield_predictions_unique
    unique (province_id, crop_start_year, model_version)
);

create table if not exists public.rice_prediction_intervals (
  id bigint generated by default as identity primary key,
  province_id integer not null references public.rice_provinces(id) on delete cascade,
  crop_start_year integer not null check (crop_start_year between 1900 and 2200),
  predicted_yield double precision not null,
  lower_90 double precision not null,
  upper_90 double precision not null,
  interval_width double precision not null check (interval_width >= 0),
  covered boolean,
  interval_method text not null,
  nominal_coverage double precision not null check (nominal_coverage between 0 and 1),
  prediction_source text not null,
  created_at timestamptz not null default now(),
  constraint rice_prediction_intervals_unique
    unique (province_id, crop_start_year, interval_method)
);

create table if not exists public.rice_shap_global (
  feature text primary key,
  feature_group text not null,
  mean_abs_shap double precision not null check (mean_abs_shap >= 0),
  mean_signed_shap double precision,
  importance_percent double precision not null check (importance_percent >= 0),
  rank integer not null check (rank > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.rice_shap_group (
  feature_group text primary key,
  mean_abs_shap double precision not null check (mean_abs_shap >= 0),
  importance_percent double precision not null check (importance_percent >= 0),
  rank integer not null check (rank > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.rice_model_metadata (
  model_version text primary key,
  model_name text not null,
  target text not null,
  target_unit text not null,
  feature_count integer not null check (feature_count > 0),
  development_period text not null,
  final_test_period text not null,
  parameters jsonb not null default '{}'::jsonb,
  test_metrics jsonb not null default '{}'::jsonb,
  notes jsonb not null default '[]'::jsonb,
  interval_metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists rice_environment_monthly_year_month_idx
  on public.rice_environment_monthly (year, month, province_id);
create index if not exists rice_yield_yearly_year_idx
  on public.rice_yield_yearly (crop_start_year, province_id);
create index if not exists rice_yield_predictions_year_idx
  on public.rice_yield_predictions (crop_start_year, province_id);

